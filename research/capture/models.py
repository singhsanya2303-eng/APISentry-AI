"""Contracts for controlled experiments and retained request metadata."""

from datetime import datetime
from enum import Enum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class EventLabel(str, Enum):
    NORMAL = "normal"
    ATTACK = "attack"


class CaptureKind(str, Enum):
    PRIMARY = "primary"
    REDIRECT = "redirect"
    PREFLIGHT = "preflight"
    STATIC_ASSET = "static_asset"
    BACKGROUND = "background_polling"
    UNRELATED = "unrelated"
    AMBIGUOUS = "ambiguous"


class ActionPhase(str, Enum):
    SETUP = "setup"
    EXECUTION = "execution"
    CLEANUP = "cleanup"


class RequestMappingPolicy(BaseModel):
    """Controls which classified requests may enter the dataset."""

    model_config = ConfigDict(extra="forbid")

    retained_kinds: set[CaptureKind] = Field(
        default_factory=lambda: {CaptureKind.PRIMARY}
    )
    api_path_prefixes: list[str] = Field(default_factory=list)
    exclude_static_assets: bool = True
    exclude_background: bool = True
    exclude_unrelated: bool = True
    exclude_ambiguous: bool = True

    def retains(self, kind: CaptureKind) -> bool:
        if kind is CaptureKind.STATIC_ASSET and self.exclude_static_assets:
            return False
        if kind is CaptureKind.BACKGROUND and self.exclude_background:
            return False
        if kind is CaptureKind.UNRELATED and self.exclude_unrelated:
            return False
        if kind is CaptureKind.AMBIGUOUS and self.exclude_ambiguous:
            return False
        return kind in self.retained_kinds


class ControlledAccountDefinition(BaseModel):
    model_config = ConfigDict(extra="forbid")

    account_id: str = Field(min_length=1)
    principal_id: str = Field(min_length=1)
    role: str = Field(min_length=1)


class ResourceOwnershipDeclaration(BaseModel):
    model_config = ConfigDict(extra="forbid")

    resource_id: str = Field(min_length=1)
    owner_account_id: str = Field(min_length=1)
    resource_type: str = Field(min_length=1)


class CapturePolicy(BaseModel):
    """Explicit policy for requests generated by one action."""

    model_config = ConfigDict(extra="forbid")

    retain_primary: bool = True
    retain_redirects: bool = False
    retain_preflight: bool = False
    retain_background: bool = False

    def retains(self, kind: CaptureKind) -> bool:
        return {
            CaptureKind.PRIMARY: self.retain_primary,
            CaptureKind.REDIRECT: self.retain_redirects,
            CaptureKind.PREFLIGHT: self.retain_preflight,
            CaptureKind.STATIC_ASSET: False,
            CaptureKind.BACKGROUND: self.retain_background,
            CaptureKind.UNRELATED: False,
            CaptureKind.AMBIGUOUS: False,
        }[kind]


class ExperimentAction(BaseModel):
    """One procedure step with an explicit label and expected outcome."""

    model_config = ConfigDict(extra="forbid")

    action_id: str = Field(min_length=1)
    campaign_id: str = Field(min_length=1)
    principal_id: str = Field(min_length=1)
    session_id: str = Field(min_length=1)
    label: EventLabel
    attack_category: str | None = None
    expected_outcome: str = Field(min_length=1)
    execution_timestamp: datetime | None = None
    capture_policy: CapturePolicy = Field(default_factory=CapturePolicy)
    mapping_policy: RequestMappingPolicy = Field(default_factory=RequestMappingPolicy)
    phase: ActionPhase = ActionPhase.EXECUTION
    execution: dict[str, object] = Field(default_factory=dict)
    allow_background: bool = False

    @model_validator(mode="after")
    def validate_label_category(self) -> "ExperimentAction":
        if self.label is EventLabel.NORMAL and self.attack_category is not None:
            raise ValueError("normal actions cannot have an attack category")
        if self.label is EventLabel.ATTACK and not self.attack_category:
            raise ValueError("attack actions require an attack category")
        if self.label is EventLabel.ATTACK and self.attack_category in {
            "brute_force",
            "rate_abuse",
        }:
            request_count = self.execution.get("request_count")
            delay_ms = self.execution.get("delay_ms")
            if not isinstance(request_count, int) or request_count < 1:
                raise ValueError("bounded attack actions require request_count")
            if not isinstance(delay_ms, int) or delay_ms < 0:
                raise ValueError("bounded attack actions require delay_ms")
            if request_count > 20 or delay_ms > 10_000:
                raise ValueError("attack action bounds are unsafe")
        return self


class ExperimentScenario(BaseModel):
    """A complete, ordered controlled collection procedure."""

    model_config = ConfigDict(extra="forbid")

    scenario_id: str = Field(min_length=1)
    scenario_version: str = Field(default="1.0", min_length=1)
    campaign_id: str = Field(min_length=1)
    source_dataset: str = Field(min_length=1)
    target_origin: str = Field(min_length=1)
    actions: list[ExperimentAction] = Field(min_length=1)
    crapi_commit: str = Field(min_length=1)
    capture_tool: str = Field(min_length=1)
    capture_tool_version: str = Field(min_length=1)
    controlled_accounts: list[ControlledAccountDefinition] = Field(
        default_factory=list
    )
    resource_ownership: list[ResourceOwnershipDeclaration] = Field(
        default_factory=list
    )
    setup_actions: list[ExperimentAction] = Field(default_factory=list)
    cleanup_actions: list[ExperimentAction] = Field(default_factory=list)
    success_conditions: list[str] = Field(default_factory=list)
    failure_conditions: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_actions(self) -> "ExperimentScenario":
        all_actions = [*self.setup_actions, *self.actions, *self.cleanup_actions]
        action_ids = [action.action_id for action in all_actions]
        if len(action_ids) != len(set(action_ids)):
            raise ValueError("action IDs must be unique")
        if any(action.campaign_id != self.campaign_id for action in all_actions):
            raise ValueError("all actions must use the scenario campaign ID")
        for action in self.setup_actions:
            if action.phase is not ActionPhase.SETUP:
                raise ValueError("setup_actions must use the setup phase")
        for action in self.cleanup_actions:
            if action.phase is not ActionPhase.CLEANUP:
                raise ValueError("cleanup_actions must use the cleanup phase")
        account_ids = {account.account_id for account in self.controlled_accounts}
        if any(
            resource.owner_account_id not in account_ids
            for resource in self.resource_ownership
        ):
            raise ValueError("resource ownership must reference a controlled account")
        return self


class SanitizedCapture(BaseModel):
    """Only metadata that may cross the in-memory privacy boundary."""

    model_config = ConfigDict(extra="forbid")

    event_id: str = Field(min_length=1)
    action_id: str = Field(min_length=1)
    capture_kind: CaptureKind
    timestamp: datetime
    method: str = Field(min_length=1)
    url: str = Field(min_length=1)
    status_code: int = Field(ge=100, le=599)
    latency_ms: float = Field(ge=0)
    request_size_bytes: int = Field(ge=0)
    response_size_bytes: int = Field(ge=0)
    safe_query_parameter_categories: list[str] = Field(default_factory=list)
    query_parameter_count: int = Field(ge=0)
    expected_outcome: str = Field(min_length=1)
    actual_outcome: str = Field(min_length=1)
    label: Literal["normal", "attack"]
    attack_category: str | None = None
    principal_value: str = Field(min_length=1)
    session_id: str = Field(min_length=1)
    campaign_id: str = Field(min_length=1)
